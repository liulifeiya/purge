function replacementsOf(patch) {
  return Array.isArray(patch.replacements) ? patch.replacements : [];
}

export function isPatched(source, patch) {
  const markers = Array.isArray(patch.markers) ? patch.markers : [];
  return markers.length > 0 && markers.every((m) => String(source).includes(m));
}

/**
 * Apply one patch to a source string. First occurrence only, idempotent by marker.
 * @param {string} source
 * @param {object} patch
 * @returns {{text: string, changed: boolean, applied: number, reason?: string}}
 */
export function applyHostPatch(source, patch) {
  let text = String(source || "");
  if (isPatched(text, patch)) return { text, changed: false, applied: 0, reason: "already_patched" };
  let applied = 0;
  for (const r of replacementsOf(patch)) {
    if (typeof r.pattern !== "string" || r.pattern.length === 0) continue;
    const at = text.indexOf(r.pattern);
    if (at < 0) continue;
    text = text.slice(0, at) + String(r.replace ?? "") + text.slice(at + r.pattern.length);
    applied += 1;
  }
  if (applied === 0) return { text, changed: false, applied, reason: "pattern_not_found" };
  return { text, changed: true, applied };
}

/** Apply many patches in order. */
export function applyHostPatches(source, patches = HOST_PATCHES) {
  let text = String(source || "");
  const results = [];
  for (const p of patches) {
    const r = applyHostPatch(text, p);
    text = r.text;
    results.push({ id: p.id, name: p.name, ...r, text: undefined });
  }
  return { text, results, changed: results.some((r) => r.changed) };
}
